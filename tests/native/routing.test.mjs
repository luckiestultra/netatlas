import assert from 'node:assert/strict';
import path from 'node:path';
import { mkdir, mkdtemp, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import test from 'node:test';
import { checkNativeProfiles, testLocalRouting } from '../../tools/lib/native.mjs';

test('native verification rejects stale generated profiles before executing a kernel', async()=>{
  const root=await mkdtemp(path.join(tmpdir(),'netatlas-stale-native-'));
  await mkdir(path.join(root,'src/rules/network'),{recursive:true});
  await writeFile(path.join(root,'src/rules/network/example.json'),JSON.stringify({version:1,id:'example',category:'network',entries:[{type:'domain-suffix',value:'example.test'}]}));
  await mkdir(path.join(root,'clients/mihomo/profiles'),{recursive:true});
  await writeFile(path.join(root,'clients/mihomo/profiles/default.yaml'),'stale generated bytes\n');
  await assert.rejects(()=>checkNativeProfiles({root,binaries:{mihomo:'must-not-execute',singBox:'must-not-execute'}}),/profile is stale.*npm run build/);
});

// Explicit opt-in: the normal unit suite must not download or run native tools.
// tools/native.mjs verifies pinned binaries and runs these routing assertions too.
test('both real kernels enforce suffix boundaries and canonical parent/child policies through HTTP and SOCKS5', {
  skip: process.env.PROXY_ATLAS_NATIVE_INTEGRATION !== '1',
  timeout: 60_000,
}, async () => {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
  const binaries = { mihomo: path.join(root, '.cache/bin/mihomo'), singBox: path.join(root, '.cache/bin/sing-box') };
  const result = await testLocalRouting({ root, binaries });
  assert.equal(result.status, 'passed');
  assert.ok(result.upstreamRequests > 0, 'fallback must traverse the real loopback SOCKS fixture');
  assert.deepEqual(result.serviceRulesets.map(item=>item.id).sort(), ['apple','apple-tvplus','github','github-copilot','npmjs']);
  for (const client of ['mihomo', 'singBox']) {
    for (const protocol of ['http', 'socks5']) {
      for (const behavior of ['explicit-direct', 'explicit-reject', 'fallback-reject', 'fallback-direct', 'suffix-root-reject', 'suffix-child-reject', 'suffix-similar-fallback', 'suffix-tail-fallback', 'fallback-proxy', 'apple-tv-domain-proxy', 'apple-tv-child-proxy', 'apple-tv-exact-proxy', 'copilot-exact-proxy', 'npm-service-proxy', 'apple-parent-direct', 'github-parent-direct', 'apple-tv-exact-child-parent', 'copilot-exact-child-parent']) {
        assert.ok(result.cases.some(item => item.client === client && item.protocol === protocol && item.behavior === behavior && item.status === 'passed'), `${client} ${protocol} ${behavior}`);
      }
    }
  }
});
